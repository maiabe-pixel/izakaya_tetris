export const ALL_MINOS: MinoType[] = ['I', 'O', 'T', 'S', 'Z', 'J', 'L'];

export function getMinoCells(
  type: MinoType,
  rotation: number,
  ox: number,
  oy: number,
): Point[] {
  const r = ((rotation % 4) + 4) % 4;
  return SHAPES[type][r].map((p) => ({ x: p.x + ox, y: p.y + oy }));
}

export function spawnOriginX(): number {
  return 3;
}
